"use client";

import { Check, CircleAlert, ScanSearch, X } from "lucide-react";

import { Button } from "@/components/ui/button";
import { cn } from "@/lib/cn";
import { resumerAvisIA } from "@/lib/studioHistorique";
import { formatEur, usdEnEur } from "@/lib/studioModeles";

import { echecRange } from "./AideIA";
import type { EssaiClient } from "./Fiche";
import type { AvisIA } from "./useParcours";

const SUGGESTION: Record<string, { texte: string; cls: string }> = {
  ok: { texte: "valider", cls: "bg-pos-soft text-pos" },
  a_corriger: { texte: "corriger", cls: "bg-warn-soft text-ink" },
  rejet: { texte: "rejeter", cls: "bg-neg-soft text-neg" },
};

/** « 0,12 € réel » | « ≈ 0,12 € estimé » | « coût inconnu »: never a zero for a missing cost. */
export function coutEnEuros(e: Pick<EssaiClient, "coutReelUsd" | "coutEstimeUsd">, taux: number): string {
  const reel = usdEnEur(e.coutReelUsd, taux);
  if (reel !== null) return `${formatEur(reel)} réel`;
  const estime = usdEnEur(e.coutEstimeUsd, taux);
  if (estime !== null) return `≈ ${formatEur(estime)} estimé`;
  return "coût inconnu";
}

/**
 * The same cell generated by 2 or 3 models in one launch, side by side with
 * the real photo: cost and AI opinion (a help) under each image. Aramis keeps
 * one — it is validated for the bag and the others are rejected — or none.
 * Keyboard: 1, 2, 3 keep that image; R rejects them all (handled by FileAJuger).
 */
export default function Comparaison({
  freres,
  referenceId,
  prise,
  angle,
  sku,
  nomDe,
  taux,
  avis,
  onRetenir,
  onAucune,
}: {
  freres: EssaiClient[];
  referenceId: string;
  prise: string;
  angle: string;
  sku: string | null;
  nomDe: (id: string) => string;
  taux: number;
  avis: AvisIA;
  onRetenir: (e: EssaiClient) => void;
  onAucune: () => void;
}) {
  const sansAvis = freres.filter((f) => f.verifIA === null && !avis.enCours.has(f.id) && !avis.echecs.has(f.id));
  return (
    <section aria-label={`Comparaison de ${freres.length} modèles`} className="flex flex-col gap-4">
      <div className="flex flex-wrap items-baseline justify-between gap-3">
        <p className="text-base text-ink">
          <strong className="font-semibold">Comparaison de {freres.length} modèles</strong>
          <span className="text-ink-2">
            {" "}
            · {prise} · {angle}
            {sku ? ` · pour ${sku}` : " · sans sac"}
          </span>
        </p>
        {sansAvis.length > 0 && (
          <Button variant="secondary" size="sm" onClick={() => avis.demander(sansAvis.map((f) => f.id))}>
            <ScanSearch size={14} aria-hidden /> Demander {sansAvis.length > 1 ? "les avis" : "l’avis"} IA
          </Button>
        )}
      </div>

      <div className={cn("grid gap-3", freres.length >= 3 ? "grid-cols-4" : "grid-cols-3")}>
        <figure className="min-w-0">
          {/* eslint-disable-next-line @next/next/no-img-element -- image privée servie par /api/studio/image */}
          <img src={`/api/studio/image?ref=${referenceId}`} alt="Vraie photo" className="aspect-[3/4] w-full rounded-md border border-line bg-surface-2 object-cover" />
          <figcaption className="mt-2 text-sm text-ink-2">
            <strong className="font-semibold text-ink">Ta vraie photo</strong>
            <br />
            La référence à retrouver.
          </figcaption>
        </figure>

        {freres.map((f, i) => {
          const avisLu = resumerAvisIA(f.verifIA);
          const suggestion = avisLu ? SUGGESTION[avisLu.verdict] : null;
          const echec = avis.echecs.get(f.id) ?? echecRange(f.verifIA);
          return (
            <figure key={f.id} className="flex min-w-0 flex-col">
              {/* eslint-disable-next-line @next/next/no-img-element -- image privée servie par /api/studio/image */}
              <img
                src={`/api/studio/image?essai=${f.id}`}
                alt={`Image ${i + 1} : ${nomDe(f.modele)}`}
                className="aspect-[3/4] w-full rounded-md border-2 border-line-strong bg-surface-2 object-cover"
              />
              <figcaption className="mt-2 flex flex-1 flex-col gap-1.5 text-sm">
                <span className="flex items-start justify-between gap-2">
                  <span className="min-w-0 font-semibold text-ink">
                    {i + 1}. {nomDe(f.modele)}
                  </span>
                  <kbd className="flex-none rounded-xs border border-line-strong px-1 font-mono text-xs text-ink-2">{i + 1}</kbd>
                </span>
                <span className="font-mono text-xs tabular-nums text-ink-2">{coutEnEuros(f, taux)}</span>
                <span className="text-xs text-ink-2">
                  {avis.enCours.has(f.id) ? (
                    "Avis IA en cours…"
                  ) : avisLu && suggestion ? (
                    <>
                      L’IA suggère <span className={cn("rounded-xs px-1 py-0.5 font-semibold", suggestion.cls)}>{suggestion.texte}</span>{" "}
                      <span className="font-mono">{avisLu.scoreGlobal}/100</span>
                    </>
                  ) : echec ? (
                    <span className="inline-flex items-start gap-1 text-ink">
                      <CircleAlert size={13} aria-hidden className="mt-0.5 flex-none text-neg" /> Avis IA en échec : {echec}
                    </span>
                  ) : (
                    "Pas encore d’avis IA"
                  )}
                </span>
                <Button size="sm" className="mt-auto" onClick={() => onRetenir(f)}>
                  <Check size={14} aria-hidden /> Retenir celle-ci
                </Button>
              </figcaption>
            </figure>
          );
        })}
      </div>

      <div className="flex flex-wrap items-center gap-3">
        <Button variant="secondary" onClick={onAucune}>
          <X size={16} aria-hidden /> Aucune ne convient
          <kbd className="ml-1 rounded-xs border border-current px-1 font-mono text-xs">R</kbd>
        </Button>
        <p className="max-w-[70ch] text-sm text-ink-2">
          Retenir valide l’image {sku ? `pour ${sku}` : "sans annonce"} et rejette les autres : c’est ton choix qui compte dans la réussite de chaque modèle.
          Tu as 5 secondes pour annuler.
        </p>
      </div>
    </section>
  );
}
